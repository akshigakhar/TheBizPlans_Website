#!/usr/bin/env python3
"""Generate canonical tags, sitemap.xml, and robots.txt from the site's HTML files."""
from __future__ import annotations

import argparse
from html import escape
from html.parser import HTMLParser
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://thebizplans.com"


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.robots: list[str] = []
        self.links: list[str] = []

    def handle_starttag(self, tag: str, attrs_list: list[tuple[str, str | None]]) -> None:
        attrs = {key.lower(): value or "" for key, value in attrs_list}
        if tag == "meta" and attrs.get("name", "").lower() == "robots":
            self.robots.extend(value.strip().lower() for value in attrs.get("content", "").split(","))
        if tag == "a" and attrs.get("href"):
            self.links.append(attrs["href"])


def canonical_url(page: Path) -> str:
    return f"{ORIGIN}/" if page.name == "index.html" else f"{ORIGIN}/{page.name}"


def last_modified(page: Path) -> str:
    """Return the last committed content date in the sitemap's W3C format."""
    result = subprocess.run(
        ["git", "log", "-1", "--format=%cs", "--", page.name],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )
    value = result.stdout.strip()
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        raise ValueError(f"{page.name}: cannot determine last modification date from Git")
    return value


def set_canonical(source: str, url: str, page: Path) -> str:
    tag = f'<link rel="canonical" href="{url}">'
    pattern = re.compile(r'<link\b(?=[^>]*\brel=["\'][^"\']*\bcanonical\b[^"\']*["\'])[^>]*>', re.I)
    matches = list(pattern.finditer(source))
    if matches:
        start, end = matches[0].span()
        source = source[:start] + tag + source[end:]
        for duplicate in reversed(list(pattern.finditer(source))[1:]):
            source = source[:duplicate.start()] + source[duplicate.end():]
        return source
    head = re.search(r"<head(?:\s[^>]*)?>", source, re.I)
    if not head:
        raise ValueError(f"{page.name}: cannot add a canonical because <head> is missing")
    return source[:head.end()] + "\n    " + tag + source[head.end():]


def local_html_target(raw: str) -> str | None:
    if not raw or raw.startswith(("#", "mailto:", "tel:", "javascript:", "data:", "//")):
        return None
    parsed = urlsplit(raw)
    if parsed.scheme in {"http", "https"} and parsed.netloc not in {"thebizplans.com", "www.thebizplans.com"}:
        return None
    path = unquote(parsed.path).lstrip("/")
    if not path:
        return "index.html"
    return path if path.endswith(".html") else None


def last_modified(page: Path) -> str:
    """Return the last committed date so sitemap output stays reproducible."""
    result = subprocess.run(
        ["git", "log", "-1", "--format=%cs", "--", page.name],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip() or "2026-10-01"


def generated_sitemap(pages: list[Path]) -> str:
    entries = "\n".join(
        "  <url>\n"
        f"    <loc>{escape(canonical_url(page))}</loc>\n"
        f"    <lastmod>{last_modified(page)}</lastmod>\n"
        "  </url>"
        for page in pages
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{entries}\n"
        "</urlset>\n"
    )


def generated_robots() -> str:
    return f"""# Generated by scripts/generate_seo.py. Do not edit by hand.
User-agent: *
Allow: /
Disallow: /*?*
Disallow: /.git/
Disallow: /.github/
Disallow: /docs/
Disallow: /scripts/
Disallow: /scss/
Disallow: /search

Sitemap: {ORIGIN}/sitemap.xml
"""


def update(path: Path, content: str, check: bool, stale: list[str]) -> None:
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    if existing == content:
        return
    stale.append(path.relative_to(ROOT).as_posix())
    if not check:
        path.write_text(content, encoding="utf-8")


def main() -> int:
    arg_parser = argparse.ArgumentParser()
    arg_parser.add_argument("--check", action="store_true", help="fail instead of updating stale generated files")
    arg_parser.add_argument("--pages", nargs="+", help="update only these pages and their sitemap entries, preserving unrelated metadata")
    args = arg_parser.parse_args()

    pages = sorted(ROOT.glob("*.html"), key=lambda page: (page.name != "index.html", page.name))
    page_names = {page.name for page in pages}
    if args.pages:
        unknown = set(args.pages) - page_names
        if unknown:
            arg_parser.error("Unknown pages: " + ", ".join(sorted(unknown)))
        pages = [page for page in pages if page.name in args.pages]
    stale: list[str] = []
    broken: list[str] = []

    for page in pages:
        source = page.read_text(encoding="utf-8")
        parser = PageParser()
        parser.feed(source)
        for raw in parser.links:
            target = local_html_target(raw)
            if target and target not in page_names:
                broken.append(f"{page.name}: {raw}")
        update(page, set_canonical(source, canonical_url(page), page), args.check, stale)

    sitemap = generated_sitemap(pages)
    if args.pages:
        # Keep existing entries verbatim; regenerate only explicitly selected pages.
        existing = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
        entries = {re.search(r"<loc>(.*?)</loc>", block).group(1): block
                   for block in re.findall(r"  <url>\n.*?</url>", existing, re.S)}
        for block in re.findall(r"  <url>\n.*?</url>", sitemap, re.S):
            entries[re.search(r"<loc>(.*?)</loc>", block).group(1)] = block
        sitemap = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                   '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                   + "\n".join(entries[url] for url in sorted(entries)) + "\n</urlset>\n")
    update(ROOT / "sitemap.xml", sitemap, args.check, stale)
    update(ROOT / "robots.txt", generated_robots(), args.check, stale)

    if broken:
        print("Broken internal page links:\n" + "\n".join(f"  {item}" for item in broken), file=sys.stderr)
        return 1
    if args.check and stale:
        print("Generated SEO files are stale: " + ", ".join(stale), file=sys.stderr)
        print("Run: python3 scripts/generate_seo.py", file=sys.stderr)
        return 1
    action = "Checked" if args.check else "Generated"
    print(f"{action} canonicals and sitemap metadata for {len(pages)} pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
